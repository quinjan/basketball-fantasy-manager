"""Fetch and summarize league settings. Nothing about the league is hard-coded elsewhere."""

from __future__ import annotations

from typing import Any

from fbm.yahoo.client import YahooClient
from fbm.yahoo.xmlparse import as_list, text

SCORING_TYPES = {
    "head": "H2H Categories (each category counts)",
    "headone": "H2H Most Categories (one win per week)",
    "headpoint": "H2H Points",
    "roto": "Rotisserie",
    "point": "Points",
}

SETTING_FIELDS = (
    "draft_type",
    "scoring_type",
    "uses_playoff",
    "playoff_start_week",
    "num_playoff_teams",
    "has_playoff_consolation_games",
    "uses_playoff_reseeding",
    "waiver_type",
    "waiver_rule",
    "waiver_time",
    "uses_faab",
    "post_draft_players",
    "max_teams",
    "max_weekly_adds",
    "max_adds",
    "max_games_played",
    "min_games_played",
    "trade_end_date",
    "trade_ratify_type",
    "trade_reject_time",
    "player_pool",
    "cant_cut_list",
    "can_trade_draft_picks",
    "uses_lock_eliminated_teams",
    "weekly_deadline",
    "sendbird_channel_url",
)
LEAGUE_FIELDS = (
    "league_key",
    "name",
    "season",
    "num_teams",
    "current_week",
    "start_week",
    "end_week",
    "start_date",
    "end_date",
    "draft_status",
    "weekly_deadline",
    "edit_key",
    "is_finished",
    "url",
)


def fetch_settings(client: YahooClient, league_key: str) -> dict[str, Any]:
    fc = client.get(f"league/{league_key}/settings")
    return fc["league"]


def summarize(league: dict[str, Any]) -> dict[str, Any]:
    settings = league.get("settings") or {}
    summary: dict[str, Any] = {k: text(league.get(k)) for k in LEAGUE_FIELDS if league.get(k) is not None}
    summary["settings"] = {k: text(settings.get(k)) for k in SETTING_FIELDS if settings.get(k) is not None}
    summary["settings"].pop("sendbird_channel_url", None)
    scoring = summary["settings"].get("scoring_type")
    summary["scoring_type_label"] = SCORING_TYPES.get(scoring or "", scoring)

    roster_slots = []
    for rp in as_list((settings.get("roster_positions") or {}).get("roster_position")):
        roster_slots.append(
            {
                "position": text(rp.get("position")),
                "count": int(text(rp.get("count"), "0") or 0),
                "is_starting": text(rp.get("is_starting_position"), "") == "1",
            }
        )
    summary["roster_slots"] = roster_slots

    scoring_cats, display_only = [], []
    stat_container = (settings.get("stat_categories") or {}).get("stats") or {}
    for st in as_list(stat_container.get("stat")):
        cat = {
            "stat_id": text(st.get("stat_id")),
            "name": text(st.get("name")),
            "display_name": text(st.get("display_name")),
            "higher_is_better": text(st.get("sort_order"), "1") == "1",
            "enabled": text(st.get("enabled"), "1") == "1",
        }
        if text(st.get("is_only_display_stat"), "0") == "1":
            display_only.append(cat)
        elif cat["enabled"]:
            scoring_cats.append(cat)
    summary["scoring_categories"] = scoring_cats
    summary["display_only_stats"] = display_only
    return summary


def to_markdown(summary: dict[str, Any]) -> str:
    s = summary.get("settings", {})
    lines = [
        f"# League settings — {summary.get('name', '')}",
        "",
        "> Auto-generated by `fbm settings`. Source of truth is Yahoo; do not hand-edit.",
        "",
        f"- League key: `{summary.get('league_key', '')}` · Season: {summary.get('season', '')}",
        f"- Teams: {summary.get('num_teams', '')} · Scoring: **{summary.get('scoring_type_label', '')}**",
        f"- Weeks: {summary.get('start_week', '')}–{summary.get('end_week', '')} "
        f"({summary.get('start_date', '')} → {summary.get('end_date', '')}) · Current week: "
        f"{summary.get('current_week', '')}",
        f"- Draft status: {summary.get('draft_status', '')}",
        "",
        "## Scoring categories",
        "",
        "| Category | Stat ID | Better |",
        "|---|---|---|",
    ]
    for c in summary.get("scoring_categories", []):
        lines.append(
            f"| {c['display_name']} | {c['stat_id']} | {'higher' if c['higher_is_better'] else 'lower'} |"
        )
    lines += ["", "## Roster slots", "", "| Slot | Count | Starting |", "|---|---|---|"]
    for r in summary.get("roster_slots", []):
        lines.append(f"| {r['position']} | {r['count']} | {'yes' if r['is_starting'] else 'no'} |")
    lines += ["", "## Rules", ""]
    for key, value in s.items():
        lines.append(f"- `{key}`: {value}")
    lines.append("")
    return "\n".join(lines)
