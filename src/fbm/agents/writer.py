"""Apply a render plan to disk with a manifest (data/agent_install.json) so installs are idempotent and safe.

Safety rules: a whole file is (over)written only if it is missing, already identical, or was generated by FBM and is
unchanged since (hash in the manifest). JSON configs get only FBM's key merged in (list values are merged item by
item, keeping yours); Codex TOML gets a marked block. Re-install removes what an older install added and the current
one no longer plans (e.g. the retired fbm MCP server entries). Uninstall removes exactly what the manifest says FBM
created, and leaves user-edited files alone.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from fbm.agents.render import (
    LEGACY_TOML_BEGIN,
    LEGACY_TOML_END,
    SETUP_SKILL,
    SETUP_SKILL_COPIES,
    TOML_BEGIN,
    TOML_END,
    Planned,
)

MANIFEST_PATH = Path("data") / "agent_install.json"


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load_manifest(root: Path) -> dict:
    p = root / MANIFEST_PATH
    if p.exists():
        try:
            return json.loads(p.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            pass
    return {"version": 1, "agents": {}}


def _save_manifest(root: Path, manifest: dict) -> None:
    p = root / MANIFEST_PATH
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes((json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8"))


def _write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def _prune_dirs(path: Path, root: Path) -> None:
    d = path.parent
    while d != root and d.exists() and not any(d.iterdir()):
        d.rmdir()
        d = d.parent


def _json_dump(obj: object) -> bytes:
    return (json.dumps(obj, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _apply_json(root: Path, p: Planned, prev: dict | None) -> tuple[str, dict | None]:
    f = root / p.path
    created = prev["created"] if prev else not f.exists()
    data: dict = {}
    if f.exists():
        try:
            data = json.loads(f.read_text(encoding="utf-8") or "{}")
        except json.JSONDecodeError:
            return "skipped (invalid JSON; add the fbm entry manually)", None
        if not isinstance(data, dict):
            return "skipped (unexpected JSON shape)", None
    node = data
    for k in p.key[:-1]:
        node = node.setdefault(k, {})
    rec: dict = {"key": list(p.key), "created": created}
    value = p.value
    if isinstance(value, list):
        rec["items"] = list(value)
        cur = node.get(p.key[-1])
        if isinstance(cur, list):
            value = cur + [v for v in value if v not in cur]
    if node.get(p.key[-1]) == value:
        return "unchanged", rec
    node[p.key[-1]] = value
    _write(f, _json_dump(data))
    return "merged" if not created else "wrote", rec


def _remove_json(root: Path, path: str, rec: dict) -> str | None:
    """Undo one JSON entry FBM merged (a key, or only FBM's items of a list). Returns the action, or None."""
    f = root / path
    if not f.exists():
        return None
    try:
        data = json.loads(f.read_text(encoding="utf-8") or "{}")
    except json.JSONDecodeError:
        return "kept (invalid JSON)"
    if not isinstance(data, dict):
        return "kept (unexpected JSON shape)"
    keys = rec["key"]
    chain = [data]
    for k in keys[:-1]:
        nxt = chain[-1].get(k) if isinstance(chain[-1], dict) else None
        if not isinstance(nxt, dict):
            return None
        chain.append(nxt)
    node, leaf = chain[-1], keys[-1]
    if leaf not in node:
        return None
    if "items" in rec and isinstance(node[leaf], list):
        node[leaf] = [v for v in node[leaf] if v not in rec["items"]]
        if not node[leaf]:
            del node[leaf]
    else:
        del node[leaf]
    for parent, k in zip(reversed(chain[:-1]), reversed(keys[:-1]), strict=True):
        if parent.get(k) == {}:
            del parent[k]
    if data == {} and rec.get("created"):
        f.unlink()
        _prune_dirs(f, root)
        return "removed"
    _write(f, _json_dump(data))
    return "removed fbm entry from"


def _strip_block(text: str) -> tuple[str, bool]:
    had = False
    for begin, end_marker in ((TOML_BEGIN, TOML_END), (LEGACY_TOML_BEGIN, LEGACY_TOML_END)):
        a, b = text.find(begin), text.find(end_marker)
        if a < 0 or b < 0:
            continue
        end = b + len(end_marker)
        if text[end : end + 1] == "\n":
            end += 1
        text, had = text[:a] + text[end:], True
    return text, had


def _apply_toml(root: Path, p: Planned, prev: dict | None) -> tuple[str, dict | None]:
    f = root / p.path
    created = prev["created"] if prev else not f.exists()
    text = f.read_bytes().decode("utf-8") if f.exists() else ""
    rest, had = _strip_block(text)
    for table in re.findall(r"^\[[^\]]+\]", p.content, flags=re.M):
        if re.search(rf"^{re.escape(table)}\s*$", rest, flags=re.M):
            return f"skipped ({table} already defined by you)", None
    if had:
        a = min(i for i in (text.find(TOML_BEGIN), text.find(LEGACY_TOML_BEGIN)) if i >= 0)
        new = rest[:a] + p.content + rest[a:]
    else:
        new = (rest.rstrip("\n") + "\n\n" if rest.strip() else "") + p.content
    if new == text:
        return "unchanged", {"created": created}
    _write(f, new.encode("utf-8"))
    return "wrote" if created else "merged", {"created": created}


def _remove_toml(root: Path, path: str, rec: dict) -> str | None:
    f = root / path
    if not f.exists():
        return None
    rest, had = _strip_block(f.read_bytes().decode("utf-8"))
    if not had:
        return None
    if not rest.strip() and rec.get("created"):
        f.unlink()
        _prune_dirs(f, root)
        return "removed"
    _write(f, rest.encode("utf-8"))
    return "removed fbm block from"


def install(agent: str, plan: list[Planned], root: Path) -> list[tuple[str, str]]:
    """Write `plan` under `root`; returns (action, path) pairs. Records what FBM owns in the manifest."""
    root = root.resolve()
    manifest = load_manifest(root)
    prev = manifest["agents"].get(agent, {"files": {}, "json": {}, "toml": {}})
    entry: dict = {"files": {}, "json": {}, "toml": {}}
    actions: list[tuple[str, str]] = []
    planned_json = {(p.path, p.key) for p in plan if p.kind == "json"}
    for path, rec in list(prev.get("json", {}).items()):
        if (path, tuple(rec["key"])) not in planned_json:
            action = _remove_json(root, path, rec)
            prev["json"].pop(path)
            if action:
                actions.append((f"{action} (no longer generated)", path))
    planned_toml = {p.path for p in plan if p.kind == "toml"}
    for path, rec in list(prev.get("toml", {}).items()):
        if path not in planned_toml:
            action = _remove_toml(root, path, rec)
            prev["toml"].pop(path)
            if action:
                actions.append((f"{action} (no longer generated)", path))
    for p in plan:
        f = root / p.path
        if p.kind == "json":
            action, rec = _apply_json(root, p, prev.get("json", {}).get(p.path))
            if rec:
                entry["json"][p.path] = rec
        elif p.kind == "toml":
            action, rec = _apply_toml(root, p, prev.get("toml", {}).get(p.path))
            if rec:
                entry["toml"][p.path] = rec
        else:
            data = p.content.encode("utf-8")
            cur = f.read_bytes() if f.exists() else None
            owned = prev.get("files", {}).get(p.path)
            if p.committed:
                action = "unchanged" if cur == data else "wrote"
                if cur != data:
                    _write(f, data)
                actions.append((action + " (committed setup skill)", p.path))
                continue
            if cur == data:
                action = "unchanged"
            elif cur is None or (owned and _sha(cur) == owned):
                _write(f, data)
                action = "wrote"
            elif owned:
                action = "skipped (you edited this generated file; delete it to regenerate)"
                entry["files"][p.path] = owned
            else:
                action = "skipped (existing file not generated by FBM)"
            if action in ("unchanged", "wrote"):
                entry["files"][p.path] = _sha(data)
        actions.append((action, p.path))
    planned = {p.path for p in plan}
    for path, sha in prev.get("files", {}).items():
        f = root / path
        if path not in planned and f.exists() and _sha(f.read_bytes()) == sha:
            f.unlink()
            _prune_dirs(f, root)
            actions.append(("removed (no longer generated)", path))
    manifest["agents"][agent] = entry
    _save_manifest(root, manifest)
    return actions


def uninstall(agent: str, root: Path) -> list[tuple[str, str]]:
    root = root.resolve()
    manifest = load_manifest(root)
    entry = manifest["agents"].get(agent)
    if not entry:
        return []
    actions: list[tuple[str, str]] = []
    for path, sha in entry.get("files", {}).items():
        f = root / path
        if not f.exists():
            continue
        if _sha(f.read_bytes()) != sha:
            actions.append(("kept (edited since install)", path))
            continue
        f.unlink()
        _prune_dirs(f, root)
        actions.append(("removed", path))
    for path, rec in entry.get("json", {}).items():
        action = _remove_json(root, path, rec)
        if action:
            actions.append((action, path))
    for path, rec in entry.get("toml", {}).items():
        action = _remove_toml(root, path, rec)
        if action:
            actions.append((action, path))
    del manifest["agents"][agent]
    _save_manifest(root, manifest)
    return actions


def status_files(agent: str, root: Path) -> list[tuple[str, str]]:
    root = root.resolve()
    entry = load_manifest(root)["agents"].get(agent, {})
    out = []
    for path, sha in entry.get("files", {}).items():
        f = root / path
        out.append(("missing" if not f.exists() else "ok" if _sha(f.read_bytes()) == sha else "edited", path))
    for kind in ("json", "toml"):
        for path in entry.get(kind, {}):
            out.append(("ok" if (root / path).exists() else "missing", path))
    return out


def sync_setup_skill(root: Path) -> list[str]:
    """Copy the canonical agents/skills/setup-fbm/SKILL.md to the committed per-agent copies; returns changed paths."""
    root = root.resolve()
    src = (root / "agents" / "skills" / SETUP_SKILL / "SKILL.md").read_bytes()
    changed = []
    for rel in SETUP_SKILL_COPIES:
        f = root / rel
        if not f.exists() or f.read_bytes() != src:
            _write(f, src)
            changed.append(rel)
    return changed
