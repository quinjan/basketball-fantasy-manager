"""Pure rendering of agent files from the canonical sources in agents/ (no I/O except reading the sources)."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

GENERATED_BY = "Generated by `fbm agent install` from agents/ — edit the source there, then re-run the install."

# Committed copies of the setup skill so any agent can find it in a fresh clone, before `fbm agent install`.
SETUP_SKILL = "setup-fbm"
SETUP_SKILL_COPIES = (
    ".github/skills/setup-fbm/SKILL.md",  # GitHub Copilot
    ".claude/skills/setup-fbm/SKILL.md",  # Claude Code (Cursor also reads .claude/skills)
    ".agents/skills/setup-fbm/SKILL.md",  # Codex, Gemini CLI, Cursor (shared Agent Skills folder)
)

SKILL_DIRS = {
    "copilot": ".github/skills",
    "claude-code": ".claude/skills",
    "codex": ".agents/skills",
    "cursor": ".agents/skills",
    "gemini": ".agents/skills",
}
AGENT_TARGETS = ("copilot", "claude-code", "codex", "cursor", "gemini", "generic")
# Agents whose CLI runs only one vendor's models: the reviewer can't be a different model family there.
SINGLE_VENDOR = {"claude-code": "Claude", "codex": "OpenAI", "gemini": "Gemini"}

MCP_TIMEOUT_MS = 120_000
TOML_BEGIN = "# >>> fbm MCP server (managed by `fbm agent install`; edit outside this block) >>>"
TOML_END = "# <<< fbm MCP server <<<"


@dataclass(frozen=True)
class Models:
    gm: str = ""
    reviewer: str = ""
    routine: str = ""

    def for_role(self, role: str) -> str:
        return {"gm": self.gm, "reviewer": self.reviewer, "routine": self.routine}.get(role, "")


@dataclass(frozen=True)
class Planned:
    """One planned output. kind: "file" (whole file), "json" (merge `value` at `key` path), "toml" (marked block)."""

    path: str  # repo-relative, forward slashes
    kind: str
    content: str = ""
    key: tuple[str, ...] = ()
    value: object = None
    committed: bool = False  # a committed setup-skill copy: written if missing, never removed


@dataclass(frozen=True)
class Role:
    name: str
    description: str
    model_role: str
    tools: tuple[str, ...]  # fbm MCP tool names; empty = all tools
    capabilities: tuple[str, ...]  # read | search | web
    body: str


def split_frontmatter(text: str) -> tuple[dict[str, object], str]:
    m = re.match(r"---\r?\n(.*?)\r?\n---\r?\n?", text, flags=re.S)
    if not m:
        return {}, text
    meta: dict[str, object] = {}
    for line in m.group(1).splitlines():
        if ":" not in line:
            continue
        k, v = line.split(":", 1)
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            meta[k.strip()] = tuple(x.strip().strip("\"'") for x in v[1:-1].split(",") if x.strip())
        else:
            meta[k.strip()] = v.strip("\"'")
    return meta, text[m.end() :]


def load_roles(sources: Path) -> list[Role]:
    roles = []
    for p in sorted((sources / "roles").glob("*.md")):
        meta, body = split_frontmatter(p.read_text(encoding="utf-8"))
        roles.append(
            Role(
                name=str(meta.get("name", p.stem)),
                description=str(meta.get("description", "")),
                model_role=str(meta.get("model_role", "gm")),
                tools=tuple(meta.get("tools", ()) or ()),
                capabilities=tuple(meta.get("capabilities", ()) or ()),
                body=body.lstrip("\n"),
            )
        )
    return roles


def load_skills(sources: Path) -> dict[str, str]:
    return {p.parent.name: p.read_bytes().decode("utf-8") for p in sorted((sources / "skills").glob("*/SKILL.md"))}


def mcp_command(repo_root: Path, platform: str = "", uv: str | None = None) -> tuple[str, list[str]]:
    """Absolute command for this machine: the venv's fbm-mcp if present, else `uv run --directory <repo> fbm-mcp`."""
    import shutil
    import sys

    platform = platform or sys.platform
    repo_root = repo_root.resolve()
    exe = (
        repo_root / ".venv" / "Scripts" / "fbm-mcp.exe"
        if platform.startswith("win")
        else repo_root / ".venv" / "bin" / "fbm-mcp"
    )
    if exe.exists():
        return str(exe), []
    return uv or shutil.which("uv") or "uv", ["run", "--directory", str(repo_root), "fbm-mcp"]


def _yaml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def _frontmatter(fields: list[tuple[str, str]]) -> str:
    return "---\n" + "".join(f"{k}: {v}\n" for k, v in fields) + "---\n"


def _reviewer_note(agent: str) -> str:
    vendor = SINGLE_VENDOR.get(agent)
    if not vendor:
        return ""
    return (
        "\n## Model family note\n\n"
        f"This AI agent runs only {vendor} models, so you cannot be a different model family from the GM. You run as a "
        "fresh-context subagent with this adversarial rubric instead — documented as weaker than cross-family review. "
        "Compensate: assume the GM is wrong until the tools prove otherwise, re-derive every number yourself, and "
        "always name the strongest alternative.\n"
    )


def _role_body(role: Role, agent: str, models: Models) -> str:
    body = role.body
    if role.name == "reviewer":
        if models.reviewer:
            body = body.replace("<the model you are running on>", models.reviewer)
        body = body.rstrip("\n") + "\n" + _reviewer_note(agent)
    return f"<!-- {GENERATED_BY} -->\n\n{body}"


CLAUDE_CAPS = {"read": ["Read"], "search": ["Grep", "Glob"], "web": ["WebSearch", "WebFetch"]}


def _role_file(role: Role, agent: str, models: Models) -> Planned | None:
    model = models.for_role(role.model_role)
    body = _role_body(role, agent, models)
    desc = _yaml_str(role.description)
    if agent == "copilot":
        fields = [("name", role.name), ("description", desc)]
        if model:
            fields.append(("model", _yaml_str(model)))
        if role.tools:
            tools = list(role.capabilities) + [f"fbm/{t}" for t in role.tools]
            fields.append(("tools", json.dumps(tools)))
        return Planned(f".github/agents/{role.name}.agent.md", "file", _frontmatter(fields) + body)
    if agent == "claude-code":
        fields = [("name", role.name), ("description", desc)]
        if role.tools:
            caps = [c for cap in role.capabilities for c in CLAUDE_CAPS.get(cap, [])]
            fields.append(("tools", ", ".join(caps + [f"mcp__fbm__{t}" for t in role.tools])))
        if model:
            fields.append(("model", model))
        return Planned(f".claude/agents/{role.name}.md", "file", _frontmatter(fields) + body)
    if agent == "cursor":
        fields = [("name", role.name), ("description", desc), ("model", model or "inherit")]
        return Planned(f".cursor/agents/{role.name}.md", "file", _frontmatter(fields) + body)
    if agent in ("codex", "gemini"):
        # No project-level custom-agent format we rely on: ship each role as a skill the agent can load on demand.
        lead = (
            f"Act as the FBM `{role.name}` role. Prefer running this in a fresh session/context"
            + (f" on model `{model}`" if model else "")
            + ".\n\n"
        )
        fields = [("name", f"fbm-{role.name}"), ("description", desc)]
        return Planned(f"{SKILL_DIRS[agent]}/fbm-{role.name}/SKILL.md", "file", _frontmatter(fields) + lead + body)
    return None


def _skill_files(agent: str, skills: dict[str, str]) -> list[Planned]:
    base = SKILL_DIRS.get(agent)
    if not base:
        return []
    out = []
    for name, text in skills.items():
        path = f"{base}/{name}/SKILL.md"
        out.append(Planned(path, "file", text, committed=path in SETUP_SKILL_COPIES))
    return out


def _codex_block(command: str, args: list[str]) -> str:
    return (
        f"{TOML_BEGIN}\n[mcp_servers.fbm]\ncommand = {json.dumps(command)}\nargs = {json.dumps(args)}\n"
        f"startup_timeout_sec = {MCP_TIMEOUT_MS // 1000}\ntool_timeout_sec = 300\n{TOML_END}\n"
    )


def render(agent: str, sources: Path, models: Models, command: str, args: list[str]) -> list[Planned]:
    """Plan every file for `agent`. Paths are repo-relative; the writer decides what's safe to write."""
    if agent not in AGENT_TARGETS:
        raise ValueError(f"unknown agent {agent!r}; choose one of {', '.join(AGENT_TARGETS)}")
    if agent == "generic":
        return []
    out: list[Planned] = []
    stdio = {"type": "stdio", "command": command, "args": list(args)}
    if agent == "copilot":
        server = {"type": "local", "command": command, "args": list(args), "tools": ["*"], "timeout": MCP_TIMEOUT_MS}
        out.append(Planned(".github/mcp.json", "json", key=("mcpServers", "fbm"), value=server))
        out.append(Planned(".vscode/mcp.json", "json", key=("servers", "fbm"), value=stdio))
    elif agent == "claude-code":
        out.append(Planned(".mcp.json", "json", key=("mcpServers", "fbm"), value={**stdio, "env": {}}))
        out.append(Planned("CLAUDE.md", "file", f"<!-- {GENERATED_BY} -->\n@AGENTS.md\n"))
    elif agent == "codex":
        out.append(Planned(".codex/config.toml", "toml", content=_codex_block(command, list(args))))
    elif agent == "cursor":
        out.append(Planned(".cursor/mcp.json", "json", key=("mcpServers", "fbm"), value=stdio))
        rule = _frontmatter([("description", _yaml_str("FBM operating rules")), ("alwaysApply", "true")])
        out.append(Planned(".cursor/rules/fbm.mdc", "file", rule + f"<!-- {GENERATED_BY} -->\n\nFollow @AGENTS.md.\n"))
    elif agent == "gemini":
        server = {"command": command, "args": list(args), "timeout": MCP_TIMEOUT_MS}
        out.append(Planned(".gemini/settings.json", "json", key=("mcpServers", "fbm"), value=server))
        out.append(Planned("GEMINI.md", "file", f"<!-- {GENERATED_BY} -->\n@./AGENTS.md\n"))
    for role in load_roles(sources):
        p = _role_file(role, agent, models)
        if p:
            out.append(p)
    out.extend(_skill_files(agent, load_skills(sources)))
    return out


def generic_instructions(command: str, args: list[str]) -> str:
    snippet = json.dumps({"mcpServers": {"fbm": {"command": command, "args": list(args)}}}, indent=2)
    return (
        "Generic MCP agent: FBM writes no agent files. Configure your agent manually:\n\n"
        f"1. Add this stdio MCP server (most agents accept this JSON shape):\n\n{snippet}\n\n"
        "2. Point your agent's project instructions at AGENTS.md (the FBM constitution).\n"
        "3. Load role prompts from agents/roles/ (gm, reviewer, scout) and skills from agents/skills/<name>/SKILL.md;\n"
        "   if your agent supports Agent Skills, copy agents/skills/* into its skills folder.\n"
        "4. Run the reviewer in a fresh context (ideally a different model family than the GM).\n"
    )
