from __future__ import annotations

import tomllib
from dataclasses import asdict, dataclass
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
CONFIG_DIR = PROJECT_ROOT / "config"
DATA_DIR = PROJECT_ROOT / "data"
RAW_DIR = DATA_DIR / "raw"
MEMORY_DIR = PROJECT_ROOT / "memory"
LEAGUE_CONFIG_PATH = CONFIG_DIR / "league.toml"


@dataclass(frozen=True)
class LeagueConfig:
    game_key: str
    season: str
    league_key: str
    league_name: str
    team_key: str
    team_name: str


class NotConfiguredError(RuntimeError):
    pass


def load_league_config(path: Path = LEAGUE_CONFIG_PATH) -> LeagueConfig:
    if not path.exists():
        raise NotConfiguredError("No league configured yet. Run `fbm auth` or `fbm league select`.")
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    return LeagueConfig(**data["league"])


def _toml_str(value: str) -> str:
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def save_league_config(cfg: LeagueConfig, path: Path = LEAGUE_CONFIG_PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by `fbm league select`. Non-secret identifiers only.",
        "[league]",
        *(f"{k} = {_toml_str(v)}" for k, v in asdict(cfg).items()),
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
