"""`fbm agent install`: rendering for every agent, safe writes, idempotency, uninstall, setup-skill copies."""

import json
import tomllib
from pathlib import Path

import pytest

from fbm.agents import AGENT_TARGETS, SETUP_SKILL_COPIES, Models, install, load_manifest, render, uninstall
from fbm.agents.render import mcp_command
from fbm.config import PROJECT_ROOT

SOURCES = PROJECT_ROOT / "agents"
MODELS = Models(gm="gm-model-x", reviewer="rev-model-y", routine="cheap-model-z")
CMD = str(Path("/abs/repo/.venv/bin/fbm-mcp").resolve())


def _plan(agent: str):
    return render(agent, SOURCES, MODELS, CMD, [])


@pytest.mark.parametrize("agent", [a for a in AGENT_TARGETS if a != "generic"])
def test_install_renders_valid_files(tmp_path, agent):
    actions = install(agent, _plan(agent), tmp_path)
    assert actions and not any(a.startswith("skipped") for a, _ in actions)
    files = [p for p in tmp_path.rglob("*") if p.is_file() and "data" not in p.parts]
    for f in files:
        if f.suffix == ".json":
            text = json.dumps(json.loads(f.read_text(encoding="utf-8")))
            assert json.dumps(CMD)[1:-1] in text
        elif f.suffix == ".toml":
            cfg = tomllib.loads(f.read_text(encoding="utf-8"))
            assert cfg["mcp_servers"]["fbm"]["command"] == CMD
    text = "\n".join(f.read_text(encoding="utf-8") for f in files)
    assert all(m in text for m in ("gm-model-x", "rev-model-y", "cheap-model-z"))
    assert any(f.name == "SKILL.md" and f.parent.name == "daily-gm" for f in files)


def test_role_frontmatter_per_agent():
    cop = {p.path: p for p in _plan("copilot")}
    rev = cop[".github/agents/reviewer.agent.md"].content
    assert 'model: "rev-model-y"' in rev and '"fbm/record_review"' in rev and "fbm/execute_proposal" not in rev
    assert "Model family note" not in rev
    assert 'model: "gm-model-x"' in cop[".github/agents/gm.agent.md"].content
    assert 'model: "cheap-model-z"' in cop[".github/agents/scout.agent.md"].content
    cl = {p.path: p for p in _plan("claude-code")}
    rev = cl[".claude/agents/reviewer.md"].content
    assert "model: rev-model-y" in rev and "mcp__fbm__record_review" in rev and "Model family note" in rev
    assert "tools:" not in cl[".claude/agents/gm.md"].content.split("---")[1]
    assert cl["CLAUDE.md"].content.strip().endswith("@AGENTS.md")
    assert ".agents/skills/fbm-reviewer/SKILL.md" in {p.path for p in _plan("codex")}


def test_empty_models_are_omitted():
    plan = render("copilot", SOURCES, Models(), CMD, [])
    assert all("model:" not in p.content for p in plan if p.path.startswith(".github/agents/"))


def test_idempotent_and_uninstall_only_generated(tmp_path):
    (tmp_path / ".github").mkdir()
    user_mcp = {"mcpServers": {"other": {"command": "x"}}}
    (tmp_path / ".github" / "mcp.json").write_text(json.dumps(user_mcp), encoding="utf-8")
    (tmp_path / ".github" / "agents").mkdir()
    user_agent = tmp_path / ".github" / "agents" / "gm.agent.md"
    user_agent.write_text("my own gm", encoding="utf-8")

    first = install("copilot", _plan("copilot"), tmp_path)
    assert ("skipped (existing file not generated by FBM)", ".github/agents/gm.agent.md") in first
    assert user_agent.read_text(encoding="utf-8") == "my own gm"
    merged = json.loads((tmp_path / ".github" / "mcp.json").read_text(encoding="utf-8"))
    assert merged["mcpServers"]["other"] == {"command": "x"} and merged["mcpServers"]["fbm"]["command"] == CMD

    second = install("copilot", _plan("copilot"), tmp_path)
    assert {a for a, _ in second} <= {"unchanged", "unchanged (committed setup skill)", first[0][0]} | {
        "skipped (existing file not generated by FBM)"
    }
    assert all(a != "wrote" and a != "merged" for a, _ in second)

    edited = tmp_path / ".github" / "agents" / "reviewer.agent.md"
    edited.write_text("edited by me", encoding="utf-8")
    third = install("copilot", _plan("copilot"), tmp_path)
    assert any(a.startswith("skipped (you edited") and p.endswith("reviewer.agent.md") for a, p in third)

    uninstall("copilot", tmp_path)
    assert user_agent.read_text(encoding="utf-8") == "my own gm"
    assert edited.read_text(encoding="utf-8") == "edited by me"
    assert json.loads((tmp_path / ".github" / "mcp.json").read_text(encoding="utf-8")) == user_mcp
    assert not (tmp_path / ".github" / "skills" / "daily-gm").exists()
    assert (tmp_path / ".github" / "skills" / "setup-fbm" / "SKILL.md").exists()  # committed copy stays
    assert not (tmp_path / ".vscode").exists()
    assert "copilot" not in load_manifest(tmp_path)["agents"]


def test_codex_merges_marked_block_into_user_toml(tmp_path):
    cfg = tmp_path / ".codex" / "config.toml"
    cfg.parent.mkdir()
    cfg.write_text('model = "o-x"\n', encoding="utf-8")
    install("codex", _plan("codex"), tmp_path)
    install("codex", _plan("codex"), tmp_path)
    data = tomllib.loads(cfg.read_text(encoding="utf-8"))
    assert data["model"] == "o-x" and data["mcp_servers"]["fbm"]["command"] == CMD
    assert cfg.read_text(encoding="utf-8").count("[mcp_servers.fbm]") == 1
    uninstall("codex", tmp_path)
    assert tomllib.loads(cfg.read_text(encoding="utf-8")) == {"model": "o-x"}


def test_generic_writes_nothing(tmp_path):
    assert render("generic", SOURCES, MODELS, CMD, []) == []


def test_mcp_command_prefers_venv(tmp_path):
    exe = tmp_path / ".venv" / "Scripts" / "fbm-mcp.exe"
    exe.parent.mkdir(parents=True)
    exe.write_text("", encoding="utf-8")
    assert mcp_command(tmp_path, platform="win32") == (str(exe.resolve()), [])
    cmd, args = mcp_command(tmp_path, platform="linux", uv="/usr/bin/uv")
    assert cmd == "/usr/bin/uv" and args == ["run", "--directory", str(tmp_path.resolve()), "fbm-mcp"]


def test_setup_skill_copies_match_canonical():
    canonical = (SOURCES / "skills" / "setup-fbm" / "SKILL.md").read_bytes()
    for rel in SETUP_SKILL_COPIES:
        assert (PROJECT_ROOT / rel).read_bytes() == canonical, f"{rel} is stale: run `fbm agent sync-setup-skill`"
