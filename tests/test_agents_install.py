"""`fbm agent install`: rendering for every agent, safe writes, idempotency, uninstall, MCP-era cleanup."""

import json
import tomllib

import pytest

from fbm.agents import AGENT_TARGETS, SETUP_SKILL_COPIES, Models, install, load_manifest, render, uninstall
from fbm.agents.render import LEGACY_TOML_BEGIN, LEGACY_TOML_END, TOOL_COMMAND
from fbm.agents.writer import MANIFEST_PATH
from fbm.config import PROJECT_ROOT

SOURCES = PROJECT_ROOT / "agents"
MODELS = Models(gm="gm-model-x", reviewer="rev-model-y", routine="cheap-model-z")


def _plan(agent: str):
    return render(agent, SOURCES, MODELS)


@pytest.mark.parametrize("agent", [a for a in AGENT_TARGETS if a != "generic"])
def test_install_renders_valid_files_without_mcp(tmp_path, agent):
    actions = install(agent, _plan(agent), tmp_path)
    assert actions and not any(a.startswith("skipped") for a, _ in actions)
    files = [p for p in tmp_path.rglob("*") if p.is_file() and "data" not in p.parts]
    for f in files:
        if f.suffix == ".json":
            json.loads(f.read_text(encoding="utf-8"))
        elif f.suffix == ".toml":
            assert tomllib.loads(f.read_text(encoding="utf-8"))["sandbox_workspace_write"]["network_access"] is True
    text = "\n".join(f.read_text(encoding="utf-8") for f in files)
    assert all(m in text for m in ("gm-model-x", "rev-model-y", "cheap-model-z"))
    assert "mcp" not in text.lower()  # no MCP server config anywhere
    assert any(f.name == "SKILL.md" and f.parent.name == "daily-gm" for f in files)


def test_role_frontmatter_and_tool_scope():
    cop = {p.path: p for p in _plan("copilot")}
    rev = cop[".github/agents/reviewer.agent.md"].content
    assert 'model: "rev-model-y"' in rev and 'tools: ["read", "search", "shell"]' in rev
    assert f"`{TOOL_COMMAND} <name> key=value ...`" in rev and "`record_review`" in rev
    note = rev.split("## FBM tools you may use")[1]
    assert "`proposal_steps`" not in note and "Model family note" not in rev
    assert "## FBM tools you may use" not in cop[".github/agents/gm.agent.md"].content
    assert 'model: "gm-model-x"' in cop[".github/agents/gm.agent.md"].content
    gm_head = cop[".github/agents/gm.agent.md"].content.split("---")[1]
    assert 'tools: ["read", "edit", "search", "shell", "agent"' in gm_head and '"ask_user"' in gm_head
    assert "copilot_tools" not in cop[".github/agents/gm.agent.md"].content
    assert 'model: "cheap-model-z"' in cop[".github/agents/scout.agent.md"].content
    cl = {p.path: p for p in _plan("claude-code")}
    rev = cl[".claude/agents/reviewer.md"].content
    assert "model: rev-model-y" in rev and "tools: Read, Grep, Glob, Bash" in rev and "Model family note" in rev
    assert "tools:" not in cl[".claude/agents/gm.md"].content.split("---")[1]
    assert cl["CLAUDE.md"].content.strip().endswith("@AGENTS.md")
    assert cl[".claude/settings.json"].value == [f"Bash({TOOL_COMMAND}:*)"]
    assert ".agents/skills/fbm-reviewer/SKILL.md" in {p.path for p in _plan("codex")}


def test_empty_models_are_omitted():
    plan = render("copilot", SOURCES, Models())
