def test_idempotent_and_uninstall_only_generated(tmp_path):
    (tmp_path / ".claude").mkdir()
    user_settings = {"permissions": {"allow": ["Bash(git status)"]}, "theme": "dark"}
    settings = tmp_path / ".claude" / "settings.json"
    settings.write_text(json.dumps(user_settings), encoding="utf-8")
    (tmp_path / ".claude" / "agents").mkdir()
    user_agent = tmp_path / ".claude" / "agents" / "gm.md"
    user_agent.write_text("my own gm", encoding="utf-8")

    first = install("claude-code", _plan("claude-code"), tmp_path)
    assert ("skipped (existing file not generated by FBM)", ".claude/agents/gm.md") in first
    assert user_agent.read_text(encoding="utf-8") == "my own gm"
    merged = json.loads(settings.read_text(encoding="utf-8"))
    assert merged["permissions"]["allow"] == ["Bash(git status)", f"Bash({TOOL_COMMAND}:*)"]
    assert merged["theme"] == "dark"

    second = install("claude-code", _plan("claude-code"), tmp_path)
    assert all(a not in ("wrote", "merged") for a, _ in second)

    edited = tmp_path / ".claude" / "agents" / "reviewer.md"
    edited.write_text("edited by me", encoding="utf-8")
    third = install("claude-code", _plan("claude-code"), tmp_path)
    assert any(a.startswith("skipped (you edited") and p.endswith("reviewer.md") for a, p in third)

    uninstall("claude-code", tmp_path)
    assert user_agent.read_text(encoding="utf-8") == "my own gm"
    assert edited.read_text(encoding="utf-8") == "edited by me"
    assert json.loads(settings.read_text(encoding="utf-8")) == user_settings
    assert (tmp_path / ".claude" / "skills" / "setup-fbm" / "SKILL.md").exists()  # committed copy stays
    assert "claude-code" not in load_manifest(tmp_path)["agents"]


def test_reinstall_removes_mcp_era_entries(tmp_path):
    """An install from the MCP era left fbm server entries; re-installing removes exactly those."""
    gh = tmp_path / ".github" / "mcp.json"
    gh.parent.mkdir()
    gh.write_text(json.dumps({"mcpServers": {"fbm": {"command": "fbm-mcp"}}}), encoding="utf-8")
    vs = tmp_path / ".vscode" / "mcp.json"
    vs.parent.mkdir()
    vs.write_text(json.dumps({"servers": {"fbm": {"command": "fbm-mcp"}, "other": {"command": "x"}}}), "utf-8")
    codex = tmp_path / ".codex" / "config.toml"
    codex.parent.mkdir()
    legacy = f'{LEGACY_TOML_BEGIN}\n[mcp_servers.fbm]\ncommand = "fbm-mcp"\n{LEGACY_TOML_END}\n'
    codex.write_text('model = "o-x"\n\n' + legacy, encoding="utf-8")
    manifest = {
        "version": 1,
        "agents": {
            "copilot": {
                "files": {},
                "json": {
                    ".github/mcp.json": {"key": ["mcpServers", "fbm"], "created": True},
                    ".vscode/mcp.json": {"key": ["servers", "fbm"], "created": False},
                },
                "toml": {},
            },
            "codex": {"files": {}, "json": {}, "toml": {".codex/config.toml": {"created": False}}},
        },
    }
    (tmp_path / MANIFEST_PATH).parent.mkdir()
    (tmp_path / MANIFEST_PATH).write_text(json.dumps(manifest), encoding="utf-8")

    actions = install("copilot", _plan("copilot"), tmp_path)
    assert ("removed (no longer generated)", ".github/mcp.json") in actions and not gh.exists()
    assert json.loads(vs.read_text(encoding="utf-8")) == {"servers": {"other": {"command": "x"}}}
    assert load_manifest(tmp_path)["agents"]["copilot"]["json"] == {}

    install("codex", _plan("codex"), tmp_path)
    data = tomllib.loads(codex.read_text(encoding="utf-8"))
    assert data == {"model": "o-x", "sandbox_workspace_write": {"network_access": True}}
    uninstall("codex", tmp_path)
    assert tomllib.loads(codex.read_text(encoding="utf-8")) == {"model": "o-x"}


def test_codex_block_is_skipped_when_user_defines_the_table(tmp_path):
    cfg = tmp_path / ".codex" / "config.toml"
    cfg.parent.mkdir()
    cfg.write_text("[sandbox_workspace_write]\nnetwork_access = false\n", encoding="utf-8")
    actions = install("codex", _plan("codex"), tmp_path)
    assert any(a.startswith("skipped ([sandbox_workspace_write]") for a, _ in actions)
    assert cfg.read_text(encoding="utf-8") == "[sandbox_workspace_write]\nnetwork_access = false\n"


def test_generic_writes_nothing():
    assert render("generic", SOURCES, MODELS) == []


def test_setup_skill_copies_match_canonical():
    canonical = (SOURCES / "skills" / "setup-fbm" / "SKILL.md").read_bytes()
    for rel in SETUP_SKILL_COPIES:
        assert (PROJECT_ROOT / rel).read_bytes() == canonical, f"{rel} is stale: run `fbm agent sync-setup-skill`"
